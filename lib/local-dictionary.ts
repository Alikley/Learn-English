/** نسخهٔ نهایی بدون کلیدهای تکراری ساختگی (مثل chicken2) */
function buildDictionary(): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [k, v] of Object.entries(DICTIONARY)) {
    const key = k.replace(/2$/, "");
    if (!(key in out)) out[key] = v;
  }
  return out;
}

const FINAL_DICT = buildDictionary();

/** تعداد واژه‌های لغت‌نامه */
export const LOCAL_DICTIONARY_SIZE = Object.keys(FINAL_DICT).length;

/**
 * جست‌وجوی ترجمهٔ محلی یک واژهٔ انگلیسی.
 * @returns ترجمهٔ فارسی یا null
 */
export function lookupLocalTranslation(word: string): string | null {
  const key = word.trim().toLowerCase();
  if (!key) return null;
  if (key in FINAL_DICT) return FINAL_DICT[key];
  // شکل سادهٔ فعل‌های با «s» / «es» / «ing» / «ed»
  const candidates = [
    key.replace(/ies$/, "y"),
    key.replace(/es$/, ""),
    key.replace(/s$/, ""),
    key.replace(/ing$/, ""),
    key.replace(/ing$/, "e"),
    key.replace(/ed$/, ""),
    key.replace(/ed$/, "e"),
    key.replace(/ied$/, "y"),
  ];
  for (const c of candidates) {
    if (c.length > 2 && c in FINAL_DICT) return FINAL_DICT[c];
  }
  return null;
}
