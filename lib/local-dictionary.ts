/** نرمال‌سازی واژه برای جست‌وجو */
function normalizeWord(raw: string): string {
  return raw
    .trim()
    .toLowerCase()
    .replace(/[^a-z'\- ]/g, "")
    .replace(/\s+/g, " ");
}

/** جست‌وجوی ترجمهٔ محلی — یا null */
export function lookupLocalTranslation(raw: string): string | null {
  const word = normalizeWord(raw);
  if (!word) return null;
  return DICTIONARY[word] ?? null;
}

/** آیا واژه در لغت‌نامهٔ محلی هست؟ */
export function hasLocalTranslation(raw: string): boolean {
  return lookupLocalTranslation(raw) !== null;
}
