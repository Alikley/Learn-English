import { redirect } from "next/navigation";
import { getServerSession } from "next-auth";
import { authOptions } from "@/lib/auth";
import LandingView from "@/app/components/landing/LandingView";

// ========================================
// ریشهٔ سایت — لندینگ عمومی (v1.0.5.2 / English 1.0.1.2)
//
// رفع باگ «بعد از ساخت اکانت، لندینگ پیج دیگر نشان داده نشود»:
// این صفحه حالا کامپوننتِ سروری است. پیش از رندر، نشستِ کاربر
// روی سرور چک می‌شود؛ کاربرِ واردشده (با رکورد معتبر در دیتابیس)
// با redirect سروری به /home فرستاده می‌شود — یعنی HTML لندینگ
// اصلاً به مرورگر او نمی‌رسد و دیگر حتی یک فلشِ لحظه‌ای از صفحهٔ
// بازاریابی دیده نمی‌شود. مهمان (بدون کوکی سشن) همان لندینگ را
// می‌بیند؛ همان رفتار v1.0.5.0 برای بازدیدکنندهٔ جدید.
//
// نکته: session callback در lib/auth (v1.0.5.1) وجود رکورد کاربر را
// در دیتابیس چک می‌کند؛ کوکیِ سرگردانِ دیتابیسِ قبلی → بدون user.id
// → مهمان حساب می‌شود و لندینگ می‌بیند (و AuthContext کوکی را پاک
// می‌کند). بنابراین این مسیر با همان منطق ضد-کوکی-سرگردان هماهنگ است.
// ========================================

export default async function RootPage() {
  const session = await getServerSession(authOptions);

  // کاربرِ واردشده → مستقیم به پنل اصلی، بدون رندر لندینگ
  if (session?.user?.id) {
    redirect("/home");
  }

  // مهمان → لندینگ عمومی
  return <LandingView />;
}
